/**
 * TON PRIMES — the run journal (`TESTNET_MASTER_PLAN.md` §2 `journal.ts`, §5.1).
 *
 * `docs/audit/testnet-run-<date>.md` is a deliverable the plan calls "generated,
 * never hand-written", and it had no generator: the 2026-09-17 record was typed
 * out of scrollback, which is why its item 11 asserted the floor guard from a
 * transaction that never reached the pool.
 *
 * One JSON file per genesis, at `<repo>/.testnet-run/run-<subwallet>.json`,
 * gitignored alongside `.cast.json`. Every step is appended as it happens, so a
 * run that dies halfway still leaves the half it did.
 *
 *   npx tsx contracts/scripts/testnet/journal.ts show      # what has run
 *   npx tsx contracts/scripts/testnet/journal.ts render     # markdown to stdout
 */
import fs from 'fs';
import path from 'path';
import { REPO } from './sender';
import { envOpt } from './chain';
import type { AssertResult } from './assert';

export type Step = {
    phase: string;
    op: string;
    at: string;
    ok: boolean;
    tx?: string;
    before?: Record<string, string>;
    after?: Record<string, string>;
    asserts: { name: string; ok: boolean; getMethod: string; detail: string }[];
    costTon?: number;
    note?: string;
};

export type Journal = { genesis: string; startedAt: string; steps: Step[] };

function file(): string {
    const dir = path.join(REPO, '.testnet-run');
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
    const id = envOpt('PRIMES_DEPLOY_SUBWALLET_ID') ?? 'unknown';
    return path.join(dir, `run-${id}.json`);
}

export function load(): Journal {
    const f = file();
    if (!fs.existsSync(f)) {
        return {
            genesis: envOpt('PRIMES_DEPLOY_SUBWALLET_ID') ?? 'unknown',
            startedAt: new Date().toISOString(),
            steps: [],
        };
    }
    return JSON.parse(fs.readFileSync(f, 'utf8'));
}

/** Append one step. Idempotence is the CHAIN's job; this only records. */
export function record(step: Omit<Step, 'at'> & { at?: string }): void {
    const j = load();
    j.steps.push({ ...step, at: step.at ?? new Date().toISOString() });
    fs.writeFileSync(file(), JSON.stringify(j, null, 2));
}

/** Has this phase/op already recorded a success? Lets a re-run skip cheaply. */
export function done(phase: string, op: string): boolean {
    return load().steps.some((s) => s.phase === phase && s.op === op && s.ok);
}

export function fromAsserts(rs: AssertResult[]): Step['asserts'] {
    // A red assert keeps its readings: without them a failed step cannot be
    // diagnosed after the run (the 2026-09-24 flush-refuse red had none).
    return rs.map((r) => ({
        name: r.name,
        ok: r.ok,
        getMethod: r.getMethod,
        detail: r.ok ? r.detail : `${r.detail} [before ${r.before ?? '—'} → after ${r.after ?? '—'}]`,
    }));
}

export function render(j = load()): string {
    const date = j.startedAt.slice(0, 10);
    const failed = j.steps.filter((s) => !s.ok);
    const asserts = j.steps.flatMap((s) => s.asserts);
    const out: string[] = [];
    out.push(`# Testnet run — the \`${j.genesis}\` set, ${date}`);
    out.push('');
    out.push(
        'Generated by `contracts/scripts/testnet/journal.ts render` from the run journal. ' +
            'A dated measurement, not a work list. Procedure: `TESTNET_MASTER_PLAN.md`; set: ' +
            "`docs/testnet-deployment.md`'s LIVE table."
    );
    out.push('');
    out.push(
        `**${j.steps.length} steps · ${asserts.filter((a) => a.ok).length}/${asserts.length} asserts passed · ` +
            `${failed.length} step(s) failed.**`
    );
    out.push('');
    out.push('| # | phase | op | result | asserts | tx |');
    out.push('|---|---|---|---|---|---|');
    j.steps.forEach((s, i) => {
        const a = s.asserts.length
            ? `${s.asserts.filter((x) => x.ok).length}/${s.asserts.length}`
            : '—';
        const tx = s.tx ? `[trace](https://testnet.tonviewer.com/transaction/${s.tx})` : '—';
        out.push(`| ${i + 1} | ${s.phase} | \`${s.op}\` | ${s.ok ? 'OK' : '**FAILED**'} | ${a} | ${tx} |`);
    });
    out.push('');
    out.push('## Every assert, with the get-method that re-checks it');
    out.push('');
    out.push('| step | assert | get-method | reading |');
    out.push('|---|---|---|---|');
    j.steps.forEach((s) => {
        for (const a of s.asserts) {
            out.push(
                `| ${s.phase}/${s.op} | ${a.ok ? '' : '**'}${a.name}${a.ok ? '' : '**'} | ` +
                    `\`${a.getMethod}\` | ${a.detail.replace(/\|/g, '\\|')} |`
            );
        }
    });
    if (failed.length) {
        out.push('');
        out.push('## Steps that failed');
        out.push('');
        for (const s of failed) {
            out.push(`- **${s.phase}/${s.op}** — ${s.note ?? 'see asserts above'}`);
        }
    }
    out.push('');
    out.push(
        '> A run is not finished until `txAudit.ts --since <window>` is also clean: a ' +
            'non-bounceable failure credits the value before the compute phase throws, so every ' +
            'figure above can reconcile while the trace is red (MISTAKES.md 2026-09-17).'
    );
    out.push('');
    return out.join('\n');
}

if (require.main === module) {
    const cmd = process.argv[2] ?? 'show';
    if (cmd === 'render') {
        process.stdout.write(render());
    } else {
        const j = load();
        console.log(`${j.genesis}: ${j.steps.length} steps since ${j.startedAt}`);
        for (const s of j.steps) {
            const a = s.asserts.filter((x) => !x.ok).length;
            console.log(
                `  ${s.ok ? 'OK  ' : 'FAIL'} ${s.phase.padEnd(4)} ${s.op.padEnd(28)} ` +
                    `${s.asserts.length} asserts${a ? `, ${a} FAILED` : ''}`
            );
        }
    }
}
