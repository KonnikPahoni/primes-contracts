interface TraceEvent {
    mint_index: number;
    n: number;
    kind: 'prime' | 'composite';
    t: number;
    referral_number: number | null;
    factors: Record<string, number>;
}

interface Trace {
    meta: { seed_t_ton: number; seed_s_primes: number };
    events: TraceEvent[];
    summary: {
        final_head: number;
        final_T: number;
        final_S: number;
        final_pending: number;
        owed: Record<string, number>;
        claimed_total: Record<string, number>;
    };
}

function loadTrace(): Trace | null {
    if (!fs.existsSync(TRACE_PATH)) {
        return null;
    }
    const raw = fs.readFileSync(TRACE_PATH, 'utf-8');
    return JSON.parse(raw);
}

