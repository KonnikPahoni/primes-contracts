            // The table is only worth anything if every row resolves. A typo in a
            // params path or a renamed constant must fail LOUDLY here rather than
            // quietly dropping a row from the checks below.
            const failures: string[] = [];
            for (const b of BINDINGS) {
                try {
                    declared(b.file, b.name);
                    b.expected();
                } catch (e) {
                    failures.push(`${b.name}: ${(e as Error).message}`);
                }
            }
            expect(failures).toEqual([]);
            // 67 at D-168: the custody ladder (4 terms + 4 vote multipliers, two
            // contracts), the staking ladder (4 terms + 4 weights + ACC_SCALE, two
            // contracts) and the epoch twice, on top of the non-ladder rows.
            expect(BINDINGS.length).toBeGreaterThanOrEqual(67);
