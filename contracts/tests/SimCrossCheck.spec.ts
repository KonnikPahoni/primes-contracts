// TON PRIMES — sim/chain cross-check (docs/phase3-report.md §7 item 1, the task
// brief's own "single most important test").
//
// Replays a trace exported by /sim/scripts/export_trace.py --mode chain-replay
// through the real primes_ledger.tolk / primes_item.tolk contracts in
// @ton/sandbox, mint by mint, and asserts the on-chain T (getFloorNum), S
// (getFloorDen), pending, and per-prime cumulative tribute credited match the
// Python engine's own numbers for the identical mint sequence, within a
// documented rounding tolerance (float accumulation on the Python side vs.
// exact integer nanoGRAM arithmetic on-chain; k(t) is also computed by two
// different approximations — an exact math.log/exp on the Python side, a
// fixed-point log10/Taylor-series approximation on-chain, kMaxOf/kOfT in
// primes_ledger.tolk — so per-mint rebates are expected to differ by a small
// bounded amount that can compound over many mints; see the tolerance
// constants below and docs/phase3-report.md §7/§8 for the numbers this run
// actually produced).
//
// Scope, stated explicitly (this is a cross-check of the mint/split/rebate
// core, not of subsystems that don't exist on-chain yet): the trace this test
// consumes is generated with reservations, whale dumps, sandwich bots, the
// constellation multiplier, and DeDust flush all disabled — none of those
// have a live on-chain counterpart yet (reservation book / auction / venue
// timelock are unbuilt; DeDust flush is guard-logic-only, D6). Claims are
// also not replayed on-chain (nothing calls claim_tribute in this test); the
// per-prime comparison is therefore against Python's owed+claimed_total
// (i.e. total tribute ever credited to that prime), not against Python's
// post-claim "owed" alone.
//
// WHERE THE OTHER SIM CROSS-CHECKS LIVE. This file is the mint/split/rebate core's
// harness, not the only one. CONCEPT.md §4.4 point 1a's desirability ladder — the D(n)
// weight vector, the single clamp, and PREMIUM_UNIT — is pinned against
// `sim/primes_sim/desirability.py`'s output in `shared/params.json` by
// `ReservationPricing.spec.ts`, which asserts the on-chain score for the sim's whole
// published worked-examples table. It lives there rather than here because it needs the
